export default function App() {
  const [activeTab, setActiveTab] = useState<Tab>('words')
  const [settings, setSettings] = useState<AppSettings | null>(null)

  useEffect(() => {
    getSettings().then(setSettings)
  }, [])

  // Apply theme
  useEffect(() => {
    if (!settings) return
    const root = document.documentElement
    if (settings.theme === 'dark') root.setAttribute('data-theme', 'dark')
    else if (settings.theme === 'light') root.setAttribute('data-theme', 'light')
    else root.removeAttribute('data-theme')
  }, [settings?.theme])

  const handleSettingsChange = useCallback(() => {
    getSettings().then(setSettings)
  }, [])

  return (
    <ToastProvider>
      <div className="app-shell">
        <main className="page" role="main">
          {activeTab === 'words' && <WordsTab />}
          {activeTab === 'practice' && <PracticeTab />}
          {activeTab === 'grammar' && <GrammarTab />}
          {activeTab === 'progress' && <ProgressTab />}
          {activeTab === 'settings' && <SettingsTab onSettingsChange={handleSettingsChange} />}
        </main>

        <nav className="bottom-nav" aria-label="Main navigation">
          {NAV_ITEMS.map(item => (
            <button
              key={item.id}
              className={`nav-item${activeTab === item.id ? ' active' : ''}`}
              onClick={() => setActiveTab(item.id)}
              aria-current={activeTab === item.id ? 'page' : undefined}
              aria-label={item.label}
            >
              {item.icon}
              <span>{item.label}</span>
            </button>
          ))}
        </nav>
      </div>
    </ToastProvider>
  )
}

